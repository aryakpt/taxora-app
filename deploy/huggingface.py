"""Deploy the API (backend/) as a Docker Space on Hugging Face.

    python deploy/huggingface.py env      # create the Space if needed and set its settings and secrets
    python deploy/huggingface.py push     # upload backend/ (the Space rebuilds from the Dockerfile)
    python deploy/huggingface.py status   # build/runtime stage and the API's URL
    python deploy/huggingface.py logs     # the last lines of the running container's log
    python deploy/huggingface.py github   # store HF_TOKEN and HF_SPACE in this GitHub repo for auto-deploy

Locally the token comes from deploy/.env.production; in GitHub Actions from the HF_TOKEN secret and the
HF_SPACE variable. Secret values are sent straight to Hugging Face; only their names are printed.
"""

import os
import secrets
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from huggingface_hub import HfApi
from prodenv import ENV_FILE, production_env, read_env_file

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
SPACE_NAME = "taxora-api"
PORT = "8000"

# Plain settings (visible in the Space's settings page). Secrets are set separately, below.
SETTINGS = {
    "APP_ENV": "production",
    "PORT": PORT,
    "AUTH_COOKIE_SECURE": "true",
    "AUTH_COOKIE_SAMESITE": "lax",
    "TRUSTED_PROXY_HOPS": "2",
    "LLM_BASE_URL": "https://generativelanguage.googleapis.com/v1beta/openai/",
    "LLM_MODEL": "gemini-3.5-flash-lite",
    "LLM_FALLBACK_MODELS": '["gemini-3.8-flash"]',
    "LLM_DATA_POLICY": "no_training",
    "EMBEDDING_MODEL": "gemini-embedding-001",
    "EMBEDDING_DIMENSIONS": "768",
    "MAX_UPLOAD_BYTES": "31457280",
    "SUPABASE_STORAGE_BUCKET": "documents",
}
SECRETS = ("DATABASE_URL", "SUPABASE_URL", "SUPABASE_SECRET_KEY", "LLM_API_KEY", "AUTH_SECRET_KEY")
PUBLIC_FROM_FILE = ("FRONTEND_ORIGIN", "GOOGLE_CLIENT_ID")

# The Space's README: Hugging Face reads its front matter to build and run the Docker image.
SPACE_README = f"""---
title: Taxora API
emoji: 🧾
colorFrom: green
colorTo: blue
sdk: docker
app_port: {PORT}
pinned: false
short_description: Backend API of Taxora, an Indonesian tax assistant
---

Backend of [Taxora](https://github.com/aryakpt/taxora-app). This Space is deployed from GitHub; do not edit it
here. The web app is served separately and calls this API through its own origin.
"""

# What the image needs (mirrors backend/.dockerignore): no tests, no local files or secrets.
UPLOAD = ("Dockerfile", "start.sh", "alembic.ini", "requirements.txt", "app", "migrations")


def config() -> tuple[str, str, dict[str, str]]:
    values = read_env_file() if ENV_FILE.exists() else {}
    token = os.environ.get("HF_TOKEN") or values.get("HF_TOKEN")
    if not token:
        sys.exit("Fill in HF_TOKEN in deploy/.env.production (a Hugging Face token with write access).")
    space = os.environ.get("HF_SPACE") or values.get("HF_SPACE")
    if not space:
        space = f"{HfApi(token=token).whoami()['name']}/{SPACE_NAME}"
    return token, space, values


def api_url(space: str) -> str:
    owner, name = space.split("/")
    return f"https://{owner.lower().replace('_', '-').replace('.', '-')}-{name.lower()}.hf.space"


def ensure_auth_secret(values: dict[str, str]) -> str:
    """One stable signing key for sessions, generated once and kept in deploy/.env.production."""
    if values.get("AUTH_SECRET_KEY"):
        return values["AUTH_SECRET_KEY"]
    key = secrets.token_hex(32)
    with ENV_FILE.open("a") as file:
        file.write(f"\n# Generated by deploy/huggingface.py: signs login sessions. Changing it signs everyone out.\n"
                   f"AUTH_SECRET_KEY={key}\n")
    print("  generated AUTH_SECRET_KEY (saved in deploy/.env.production)")
    return key


def set_env(api: HfApi, space: str, values: dict[str, str]) -> None:
    api.create_repo(space, repo_type="space", space_sdk="docker", exist_ok=True)
    env = production_env(values)
    env["AUTH_SECRET_KEY"] = ensure_auth_secret(values)
    for key in SECRETS:
        api.add_space_secret(space, key, env[key])
        print(f"  secret   {key}")
    plain = {**SETTINGS, **{key: values[key] for key in PUBLIC_FROM_FILE if values.get(key)}}
    for key, value in plain.items():
        api.add_space_variable(space, key, value)
        print(f"  variable {key}")


def push(api: HfApi, space: str) -> None:
    api.create_repo(space, repo_type="space", space_sdk="docker", exist_ok=True)
    with tempfile.TemporaryDirectory() as staging:
        stage = Path(staging)
        for name in UPLOAD:
            source = BACKEND / name
            if source.is_dir():
                shutil.copytree(source, stage / name, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
            else:
                shutil.copy2(source, stage / name)
        (stage / "README.md").write_text(SPACE_README)
        commit = os.environ.get("GITHUB_SHA", "")[:7] or subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], check=False, cwd=ROOT, capture_output=True, text=True).stdout.strip()
        api.upload_folder(folder_path=stage, repo_id=space, repo_type="space",
                          commit_message=f"Deploy {commit} from GitHub",
                          delete_patterns=["app/**", "migrations/**"])  # drop files removed from the repo
    print(f"pushed {commit} to https://huggingface.co/spaces/{space}; it rebuilds now (a few minutes)")


def status(api: HfApi, space: str) -> None:
    runtime = api.get_space_runtime(space)
    print(f"stage: {runtime.stage}  hardware: {runtime.hardware}")
    print(f"API:   {api_url(space)}")


def logs(token: str, space: str) -> None:
    import httpx

    url = f"https://huggingface.co/api/spaces/{space}/logs/run"
    lines = []
    try:
        with httpx.stream("GET", url, headers={"Authorization": f"Bearer {token}"}, timeout=8) as response:
            for line in response.iter_lines():
                if line.startswith("data:"):
                    lines.append(line[5:].strip())
    except httpx.ReadTimeout:
        pass  # the log is a stream that stays open; what arrived so far is enough
    print("\n".join(lines[-60:]) or "(no log lines)")


def github(token: str, space: str) -> None:
    subprocess.run(["gh", "secret", "set", "HF_TOKEN"], input=token, text=True, check=True, cwd=ROOT)
    subprocess.run(["gh", "variable", "set", "HF_SPACE", "--body", space], check=True, cwd=ROOT)
    print(f"GitHub: secret HF_TOKEN and variable HF_SPACE={space} set")


if __name__ == "__main__":
    actions = ("env", "push", "status", "logs", "github")
    if len(sys.argv) != 2 or sys.argv[1] not in actions:
        sys.exit(__doc__)
    token, space, values = config()
    api = HfApi(token=token)
    action = sys.argv[1]
    if action == "env":
        set_env(api, space, values)
        print(f"Space {space} configured; run `make deploy-api` to upload the code.")
    elif action == "push":
        push(api, space)
    elif action == "status":
        status(api, space)
    elif action == "logs":
        logs(token, space)
    else:
        github(token, space)
