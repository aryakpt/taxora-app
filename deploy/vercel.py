"""Deploy Taxora (frontend and API, one Vercel project; see vercel.json) with the token from
deploy/.env.production.

    python deploy/vercel.py env       # set the production environment variables (secrets included)
    python deploy/vercel.py deploy    # build and deploy to production
    python deploy/vercel.py logs      # recent runtime logs of the production deployment

The token reaches the Vercel CLI through its environment and the REST API through a header, so it never
appears in a command line; variable values are sent to Vercel and only their names are printed.
"""

import json
import os
import secrets
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

from prodenv import ENV_FILE, production_env, read_env_file

ROOT = Path(__file__).resolve().parents[1]
PROJECT_FILE = ROOT / ".vercel" / "project.json"

# Plain settings for the API service. Secrets are added from deploy/.env.production below.
SETTINGS = {
    "APP_ENV": "production",
    "AUTH_COOKIE_SECURE": "true",
    "AUTH_COOKIE_SAMESITE": "lax",
    # Vercel replaces X-Forwarded-For with the visitor's address, so one trusted hop.
    "TRUSTED_PROXY_HOPS": "1",
    # Serverless: documents are processed inside the request (max 300 s), and Vercel accepts request bodies up
    # to 4.5 MB; larger documents are submitted by their official link.
    "INGESTION_INLINE": "true",
    "INGESTION_STALE_MINUTES": "10",
    "MAX_UPLOAD_BYTES": str(4 * 2**20),
    "LLM_BASE_URL": "https://generativelanguage.googleapis.com/v1beta/openai/",
    "LLM_MODEL": "gemini-3.5-flash-lite",
    "LLM_FALLBACK_MODELS": '["gemini-3.8-flash"]',
    "LLM_DATA_POLICY": "no_training",
    "EMBEDDING_MODEL": "gemini-embedding-001",
    "EMBEDDING_DIMENSIONS": "768",
    "SUPABASE_STORAGE_BUCKET": "documents",
}
SECRETS = ("DATABASE_URL", "SUPABASE_URL", "SUPABASE_SECRET_KEY", "LLM_API_KEY", "AUTH_SECRET_KEY")
PUBLIC_FROM_FILE = ("FRONTEND_ORIGIN", "GOOGLE_CLIENT_ID")


def token(values: dict[str, str]) -> str:
    if not values.get("VERCEL_TOKEN"):
        sys.exit("Fill in VERCEL_TOKEN in deploy/.env.production.")
    return values["VERCEL_TOKEN"]


def cli(values: dict[str, str], *args: str) -> int:
    return subprocess.call(["npx", "--yes", "vercel@latest", *args], cwd=ROOT,
                           env={**os.environ, "VERCEL_TOKEN": token(values)})


def link(values: dict[str, str]) -> dict:
    """Link the repository root to the Vercel project (created on first use)."""
    if not PROJECT_FILE.exists():
        project = values.get("VERCEL_PROJECT", "taxora")
        if cli(values, "link", "--yes", "--project", project):
            sys.exit("vercel link failed")
    return json.loads(PROJECT_FILE.read_text())


def ensure_auth_secret(values: dict[str, str]) -> str:
    """One stable session signing key, generated once and kept in deploy/.env.production."""
    if values.get("AUTH_SECRET_KEY"):
        return values["AUTH_SECRET_KEY"]
    key = secrets.token_hex(32)
    with ENV_FILE.open("a") as file:
        file.write("\n# Generated by deploy/vercel.py: signs login sessions. Changing it signs everyone out.\n"
                   f"AUTH_SECRET_KEY={key}\n")
    print("  generated AUTH_SECRET_KEY (saved in deploy/.env.production)")
    return key


def api(values: dict[str, str], project: dict, method: str, path: str, body=None):
    team = project.get("orgId", "")
    query = f"{'&' if '?' in path else '?'}teamId={team}" if team.startswith("team_") else ""
    request = urllib.request.Request(
        f"https://api.vercel.com{path}{query}", method=method,
        data=json.dumps(body).encode() if body is not None else None,
        headers={"Authorization": f"Bearer {token(values)}", "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.loads(response.read() or b"null")
    except urllib.error.HTTPError as exc:
        sys.exit(f"Vercel API {method} {path}: {exc.code} {exc.read().decode()[:300]}")


def set_env(values: dict[str, str]) -> None:
    project = link(values)
    env = production_env(values)
    env["AUTH_SECRET_KEY"] = ensure_auth_secret(values)
    variables = {**{key: (env[key], "sensitive") for key in SECRETS},
                 **{key: (value, "plain") for key, value in SETTINGS.items()},
                 **{key: (values[key], "plain") for key in PUBLIC_FROM_FILE if values.get(key)}}
    for key, (value, kind) in variables.items():
        api(values, project, "POST", f"/v10/projects/{project['projectId']}/env?upsert=true",
            {"key": key, "value": value, "type": kind, "target": ["production"]})
        print(f"  {kind:<9} {key}")


if __name__ == "__main__":
    actions = ("env", "deploy", "logs")
    if len(sys.argv) < 2 or sys.argv[1] not in actions:
        sys.exit(__doc__)
    values = read_env_file()
    if sys.argv[1] == "env":
        set_env(values)
        print("Production variables set; they apply from the next deploy (make deploy).")
    elif sys.argv[1] == "deploy":
        link(values)
        sys.exit(cli(values, "deploy", "--prod", "--yes", *sys.argv[2:]))
    else:
        link(values)
        sys.exit(cli(values, "logs", *sys.argv[2:]))
